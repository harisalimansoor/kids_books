"""
PDF generation functions
"""
import os
import streamlit as st
from fpdf import FPDF
from PIL import Image
from utils import safe_text


def generate_pdf(
    student_name: str,
    grade: str,
    topic_header_text: str,
    questions: list,
    image_paths: list = None
) -> bytes:
    """
    Generate a PDF workbook with questions and optional images.
    """
    print(f"DEBUG PDF: Starting with {len(questions)} questions")
    print(f"DEBUG PDF: image_paths = {image_paths}")
    
    pdf = FPDF()
    pdf.add_page()
    
    # Header
    pdf.set_text_color(30, 30, 80)  # Premium Dark Blue
    pdf.set_font("Arial", "B", 18)
    grade_display = grade.replace("Grade", "Year")
    pdf.cell(0, 10, safe_text(f"Personalised Maths Workbook: {student_name} ({grade_display})"), ln=True, align="C")
    pdf.ln(2)
    
    # Topics
    pdf.set_font("Arial", "I", 12)
    pdf.set_text_color(100, 100, 100)  # Soft Grey
    pdf.cell(0, 8, safe_text(f"Focus: {topic_header_text}"), ln=True, align="C")
    pdf.ln(4)
    pdf.set_draw_color(200, 200, 200)
    pdf.line(20, pdf.get_y(), 190, pdf.get_y())
    pdf.ln(8)

    # Questions
    pdf.set_font("Arial", size=12)
    for idx, q in enumerate(questions, start=1):
        # Add image if available
        if image_paths and idx <= len(image_paths) and image_paths[idx-1]:
            try:
                img_path = image_paths[idx-1]
                target_w = 95  # Smaller image to prevent large page gaps
                try:
                    with Image.open(img_path) as img:
                        w, h = img.size
                        img_h = target_w * (h / w)
                except Exception:
                    img_h = 95
                    
                # Check if we need a new page (room for image + text + divider)
                if pdf.get_y() + img_h + 20 > 280:
                    pdf.add_page()
                    
                current_y = pdf.get_y()
                
                # Center the image: (210 page width - 95 image width) / 2 = 57.5
                pdf.image(img_path, x=57.5, y=current_y, w=target_w)
                pdf.set_y(current_y + img_h + 6)  # Place cursor nicely below
            except Exception as e:
                st.warning(f"Could not add image for question {idx}: {e}")
        else:
            if pdf.get_y() + 25 > 280:
                pdf.add_page()
        
        # Add question text
        pdf.set_text_color(40, 40, 40)  # Dark charcoal text for readability
        pdf.multi_cell(0, 8, safe_text(f"{idx}. {q}"))
        pdf.ln(6)
        
        # Elegant subtle divider
        pdf.set_draw_color(230, 230, 230)
        pdf.line(30, pdf.get_y(), 180, pdf.get_y())
        pdf.ln(8)

    # Footer
    pdf.set_y(-20)
    pdf.set_font("Arial", "I", 10)
    pdf.set_text_color(150, 150, 150)
    pdf.cell(0, 10, safe_text("Generated by the Personalised Maths App"), 0, 0, "C")

    return bytes(pdf.output())


def cleanup_temp_images(image_paths: list):
    """
    Remove temporary image files.
    
    Args:
        image_paths: List of image file paths to delete
    """
    for img_path in image_paths:
        if img_path and os.path.exists(img_path):
            try:
                os.remove(img_path)
            except Exception:
                pass