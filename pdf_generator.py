"""
PDF generation functions
"""
import os
import streamlit as st
from fpdf import FPDF
from utils import safe_text


def generate_pdf(
    student_name: str,
    grade: str,
    topic_header_text: str,
    questions: list,
    image_paths: list = None
) -> bytes:
    """
    Generate a PDF workbook with questions and optional images.
    
    Args:
        student_name: Student's name
        grade: Grade level
        topic_header_text: Topics covered
        questions: List of question strings
        image_paths: Optional list of image file paths
    
    Returns:
        PDF as bytes
    """
    pdf = FPDF()
    pdf.add_page()
    
    # Header
    pdf.set_font("Arial", "B", 16)
    pdf.cell(0, 10, safe_text(f"Math Worksheet for {student_name} - {grade}"), ln=True, align="C")
    pdf.ln(5)
    
    # Topics
    pdf.set_font("Arial", "I", 12)
    pdf.cell(0, 8, safe_text(f"Topics: {topic_header_text}"), ln=True, align="C")
    pdf.ln(5)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(10)

    # Questions
    pdf.set_font("Arial", size=12)
    for idx, q in enumerate(questions, start=1):
        # Add image if available
        if image_paths and idx <= len(image_paths) and image_paths[idx-1]:
            try:
                current_y = pdf.get_y()
                # Check if we need a new page
                if current_y > 240:
                    pdf.add_page()
                    current_y = pdf.get_y()
                
                pdf.image(image_paths[idx-1], x=15, y=current_y, w=50)
                pdf.ln(55)  # Space after image
            except Exception as e:
                st.warning(f"Could not add image for question {idx}: {e}")
        
        # Add question text
        pdf.multi_cell(0, 8, safe_text(f"{idx}. {q}"))
        pdf.ln(6)
        pdf.line(10, pdf.get_y(), 200, pdf.get_y())
        pdf.ln(8)

    # Footer
    pdf.set_y(-20)
    pdf.set_font("Arial", "I", 10)
    pdf.cell(0, 10, safe_text("Generated by Personalized Math Question Generator"), 0, 0, "C")

    return pdf.output(dest="S").encode("latin-1")


def cleanup_temp_images(image_paths: list):
    """
    Remove temporary image files.
    
    Args:
        image_paths: List of image file paths to delete
    """
    for img_path in image_paths:
        if img_path and os.path.exists(img_path):
            try:
                os.remove(img_path)
            except Exception:
                pass